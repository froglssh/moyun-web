// 清理文獻引證雜訊，保留純淨的歷史故事與寫作背景
function extractPureBackground(intro) {
  if (!intro) return '';
  let s = intro
    .replace(/^.*?選自.*?[。！]/g, '')
    .replace(/^.*?出自.*?[。！]/g, '')
    .replace(/^.*?節錄.*?[。！]/g, '')
    .replace(/版本據.*?。/g, '')
    .replace(/本篇所用版本.*?。/g, '')
    .replace(/題目為後人.*?。/g, '')
    .replace(/本篇選自.*?。/g, '')
    .replace(/《先秦兩漢古籍逐字索引》/g, '')
    .replace(/宋・王應麟：《困學記聞》引.*?云：/g, '')
    .trim();
  
  // 截取前 120 字有意義的敘述
  s = s.replace(/^[、，。；\s]+|[、，。；\s]+$/g, '');
  if (s.length > 120) {
    const end = s.indexOf('。', 60);
    s = end > 0 ? s.slice(0, end + 1) : s.slice(0, 110) + '。';
  }
  return s;
}

