// 通用合成器：賦予國文老師的親切口吻與深入淺出的串講
function buildTeacherVernacular(item, profile) {
  const key = `${item.author}|${item.title}`;
  if (CURATED[key]) return CURATED[key];

  const meaning = profile?.meaning || '';
  const reading = profile?.scenes?.[0]?.yijing?.reading || '';
  const lines = item.lines || [];
  const intro = extractPureBackground(item.intro);

  const author = item.author || '古人';
  const title = item.title || '本篇';
  const period = item.period || '';
  const form = item.form || '詩文';

  let lead = '';
  if (author.startsWith('《') || ['古歌謠', '漢樂府', '古詩十九首', '敦煌變文'].includes(author)) {
    lead = `【國文老師為你解讀】同學們好！這篇選自${author}的《${title}》（${period}·${form}），是古典文學庫中的經典名篇。`;
  } else {
    lead = `【國文老師為你解讀】同學們好！這篇由${period}名家${author}所作的《${title}》（${form}），在文學史上具有獨特的藝術價值。`;
  }

  // 1. 白話情節與創作脈絡
  let body = '';
  if (intro && intro.length > 15) {
    body += `${intro}。`;
  }

  if (['文', '小說'].includes(form)) {
    // 散文與小說類
    if (meaning) {
      body += `作者在敘事與議論中層層展開，核心主旨聚焦於：${meaning}。`;
    }
    body += `老師希望大家細細品讀文章的情節脈絡與人物言行，體會古人如何借事明理、以小見大，從歷史與故事中汲取立身處世的智慧。`;
  } else {
    // 詩詞曲賦類
    const quote = item.quote?.[0] || lines[0] || '';
    const cleanQuote = quote.replace(/[\r\n\s]+/g, ' ').slice(0, 30);
    if (cleanQuote) {
      body += `詩中寫下「${cleanQuote}……」的真摯文句，將眼前之景與內心波瀾融合得天衣無縫。`;
    }
    if (meaning) {
      body += `全篇核心寄託了：${meaning}。`;
    }
    if (reading) {
      const cleanReading = reading.split('；')[0].replace(/不把它.*|不另造.*|不畫成.*/g, '').trim();
      if (cleanReading && cleanReading !== meaning) {
        body += `意境上展現出${cleanReading}的審美風貌。`;
      }
    }
    body += `老師提醒大家，古典詩詞最迷人之處就在於『景語即情語』，字字句句都映照出作者真實的心境與人生境界，值得大家涵泳咀嚼。`;
  }

  return `${lead}${body}`;
}

